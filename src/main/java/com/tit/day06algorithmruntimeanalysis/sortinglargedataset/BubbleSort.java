package com.tit.day06algorithmruntimeanalysis.sortinglargedataset;

// Creating a class BubbleSort to represent the bubble sort algorithm
class BubbleSort {
    // Method for Bubble Sort
    public void bubbleSort(int[] arr) {
        int n = arr.length;
        for (int i = 0; i < n - 1; i++) {
            for (int j = 0; j < n - 1 - i; j++) {
                if (arr[j] > arr[j + 1]) {
                    int temp = arr[j];
                    arr[j] = arr[j + 1];
                    arr[j + 1] = temp;
                }
            }
        }
    }
}
